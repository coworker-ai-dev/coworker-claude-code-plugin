#!/usr/bin/env python3
"""Regenerate the bundled playbooks from the server-side skills.

The plugin ships a copy of the canonical MCP playbooks next to the skills that
point at them, so a model that opens the skill gets the full procedure without
a separate skill_retrieve call (which models rarely make unprompted). The
server-side skills stay the single source of truth: this script copies them in,
it never edits them.

Usage:
  scripts/sync-playbooks.py path/to/skills.json
  scripts/sync-playbooks.py -        # read the JSON from stdin

Input: a JSON array of {"name": ..., "content": ...} objects, one per skill,
exported from the Coworker admin tooling. Only the names listed in TARGETS are
used; anything else in the file is ignored.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = {
    "mcp-om2-usage": ROOT / "skills/knowledge-graph/playbook.md",
    "mcp-company-data-cascade": ROOT / "skills/company-data-first/playbook.md",
    "mcp-data-quality": ROOT / "skills/company-data-first/data-quality.md",
}
HEADER = (
    "<!-- Generated by scripts/sync-playbooks.py from the server-side skill "
    "`{name}`. Do not edit here: change the skill, then re-run the script. -->\n\n"
)


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    src = sys.stdin if sys.argv[1] == "-" else open(sys.argv[1])
    rows = json.load(src)
    if not isinstance(rows, list):
        rows = rows.get("rows") or rows.get("result") or []
    by_name = {r["name"]: r["content"] for r in rows if r.get("name") in TARGETS}
    missing = sorted(set(TARGETS) - set(by_name))
    if missing:
        print(f"missing rows: {', '.join(missing)}", file=sys.stderr)
        return 1
    for name, path in TARGETS.items():
        path.write_text(HEADER.format(name=name) + by_name[name].rstrip() + "\n")
        print(f"wrote {path.relative_to(ROOT)} ({len(by_name[name])} chars)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
